// Writes contracts/test/fixtures/gateway-response.json: real gateway answers
// that the Solidity tests feed to OffchainResolver.resolveWithProof.
//
// Everything is fixed (test key, resolver address, clock, app data), so the
// output only changes when the gateway's encoding or signing changes.
//
//   corepack pnpm --filter gateway fixture

import { writeFile } from "node:fs/promises";
import { encodeFunctionData, parseAbi, toHex, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { namehash, packetToBytes } from "viem/ens";
import { createAdapterClient } from "../src/adapter-client.ts";
import { createServer } from "../src/server.ts";

// Anvil's first well-known test key. Never use it for anything real.
const SIGNER = privateKeyToAccount("0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80");
// The Solidity test deploys the resolver at this address with deployCodeTo.
const RESOLVER = "0x5615dEB798BB3E4dFa0139dFa1b3D433Cc23b72f";
const TTL_SECONDS = 300;
const EXPIRES = 1_900_000_000;

const NAME = "happy.tradepit.eth";
const APP_RESPONSE = {
  name: "happy",
  address: "0x779981590E7Ccc0CFAe8040Ce7151324747cDb97",
  texts: { description: "Rank #2 on Tradepit" },
};

const abi = parseAbi([
  "function resolve(bytes name, bytes data) view returns (bytes)",
  "function addr(bytes32 node) view returns (address)",
  "function text(bytes32 node, string key) view returns (string)",
]);

const app = createServer({
  signer: SIGNER,
  parentName: "tradepit.eth",
  adapter: createAdapterClient({
    baseUrl: "http://app.invalid",
    fetch: async () => Response.json(APP_RESPONSE),
  }),
  ttlSeconds: TTL_SECONDS,
  now: () => (EXPIRES - TTL_SECONDS) * 1000,
});

async function lookup(recordCall: Hex) {
  const request = encodeFunctionData({
    abi,
    functionName: "resolve",
    args: [toHex(packetToBytes(NAME)), recordCall],
  });
  const response = await app.request(`/${RESOLVER}/${request}.json`);
  if (!response.ok) throw new Error(`gateway answered HTTP ${response.status}: ${await response.text()}`);

  const { data } = (await response.json()) as { data: Hex };
  return { request, response: data };
}

const fixture = {
  comment: "Generated by gateway/scripts/export-fixture.ts with a test-only key (anvil #0). Do not edit by hand.",
  signer: SIGNER.address,
  resolver: RESOLVER,
  expires: EXPIRES,
  name: NAME,
  addr: {
    ...(await lookup(encodeFunctionData({ abi, functionName: "addr", args: [namehash(NAME)] }))),
    expected: APP_RESPONSE.address,
  },
  text: {
    key: "description",
    ...(await lookup(encodeFunctionData({ abi, functionName: "text", args: [namehash(NAME), "description"] }))),
    expected: APP_RESPONSE.texts.description,
  },
};

const path = new URL("../../contracts/test/fixtures/gateway-response.json", import.meta.url);
await writeFile(path, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`Wrote ${path.pathname}`);
